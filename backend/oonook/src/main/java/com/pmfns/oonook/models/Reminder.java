package com.pmfns.oonook.models;

import com.google.cloud.firestore.annotation.DocumentId;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import com.google.cloud.spring.data.firestore.Document;

@Data
@Builder
@AllArgsConstructor
@NoArgsConstructor
@Document(collectionName = "reminders")
public class Reminder {

    @DocumentId
    private String id;
    private String userId;
    private String type;
    private String icon;
    private String label;
    private String time;
    private String status;
    private Integer daysSinceContact;
    private Boolean autoGenerated;
    private String linkedId;

    @com.google.cloud.firestore.annotation.PropertyName("days_since_contact")
    public Integer getDaysSinceContact() {
        return daysSinceContact;
    }

    @com.google.cloud.firestore.annotation.PropertyName("days_since_contact")
    public void setDaysSinceContact(Integer daysSinceContact) {
        this.daysSinceContact = daysSinceContact;
    }

    @com.google.cloud.firestore.annotation.PropertyName("auto_generated")
    public Boolean getAutoGenerated() {
        return autoGenerated;
    }

    @com.google.cloud.firestore.annotation.PropertyName("auto_generated")
    public void setAutoGenerated(Boolean autoGenerated) {
        this.autoGenerated = autoGenerated;
    }

    @com.google.cloud.firestore.annotation.PropertyName("linked_id")
    public String getLinkedId() {
        return linkedId;
    }

    @com.google.cloud.firestore.annotation.PropertyName("linked_id")
    public void setLinkedId(String linkedId) {
        this.linkedId = linkedId;
    }
}
